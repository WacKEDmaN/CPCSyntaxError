static std::unordered_map<std::string, MatrixGlyph> buildFont() {
  std::unordered_map<std::string, MatrixGlyph> font;
  for (const RawGlyph& g : RAW) {
    MatrixGlyph glyph; glyph.left = g.left; glyph.right = g.right;
    for (int r = 0; r < 18; r += 1) {
      std::string row;
      for (int c = 0; c < g.width; c += 1) row += ((g.rows[r] >> c) & 1) ? '#' : '.';
      glyph.bitmap.push_back(row);
    }
    font[std::string(g.key)] = glyph;
  }
  return font;
}

const std::unordered_map<std::string, MatrixGlyph>& nearlyqFont() {
  static const std::unordered_map<std::string, MatrixGlyph> font = buildFont();
  return font;
}

